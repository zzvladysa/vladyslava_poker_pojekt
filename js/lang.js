let currentLang = 'de';

// Подставляет значения в {0}, {1}
function fmt(text, args) {
    args.forEach(function (arg, i) { text = text.replace('{' + i + '}', arg); });
    return text;
}
// t('logSb', 'Bot 1', 10) -> текст на текущем языке
function t(key, ...args) {
    return fmt(translations[currentLang][key], args);
}
// Для списков фраз: берёт случайную (чтобы бот не повторялся)
function tPick(key, ...args) {
    const list = translations[currentLang][key];
    return fmt(list[Math.floor(Math.random() * list.length)], args);
}

function applyLanguage() {
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
        el.textContent = t(el.dataset.i18n);
    });
    document.documentElement.lang = currentLang;
}

function setLanguage(lang) {
    currentLang = lang;
    applyLanguage();
}